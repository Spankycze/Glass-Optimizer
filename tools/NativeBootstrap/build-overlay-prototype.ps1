param(
  [string]$InstallerPath,
  [string]$OutputPath,
  [string]$ExpectedVersion = ''
)
$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
if (-not $InstallerPath) { throw 'Explicit -InstallerPath is required: do not silently embed stale WPF 15.4.889.' }
if (-not $OutputPath) { $OutputPath = Join-Path $root 'artifacts\NativeBootstrap_Overlay_Prototype.exe' }
if (!(Test-Path -LiteralPath $InstallerPath -PathType Leaf)) { throw "Missing WPF installer: $InstallerPath" }
if ($ExpectedVersion) {
  $expectedName = 'Spankyho_Optimizer_V' + $ExpectedVersion.Replace('.','_') + '_Setup_Compact.exe'
  if (![string]::Equals([IO.Path]::GetFileName($InstallerPath),$expectedName,[StringComparison]::OrdinalIgnoreCase)) {
    throw ('WPF payload version mismatch: expected '+$expectedName+' but got '+[IO.Path]::GetFileName($InstallerPath))
  }
  $vi = (Get-Item -LiteralPath $InstallerPath).VersionInfo.ProductVersion
  if (-not $vi -or -not ($vi -eq $ExpectedVersion -or $vi.StartsWith(($ExpectedVersion+'+'),[StringComparison]::Ordinal))) {
    throw ('WPF ProductVersion mismatch: expected '+$ExpectedVersion+' actual '+$vi)
  }
  Write-Output ('NATIVE_WPF_VERSION_GUARD_OK ' + $ExpectedVersion)
}
$tests = Join-Path $root 'tools\NativeBootstrap.Tests\NativeBootstrap.Tests.csproj'
& dotnet run --project $tests -c Release --nologo | Out-Host
if ($LASTEXITCODE -ne 0) { throw 'Native bootstrap 44-test regression gate failed' }
Write-Output 'NATIVE_BOOTSTRAP_REGRESSION_GATE_OK count=44'
$sourceFile = Get-Item -LiteralPath $InstallerPath
$sourceHash = (Get-FileHash -LiteralPath $InstallerPath -Algorithm SHA256).Hash
$info = @"
 // Generated by build-overlay-prototype.ps1; hash and byte length are compiled into the native executable.
 internal static class PackagedInstallerInfo
 {
     internal const long Size = $($sourceFile.Length);
     internal const string Sha256 = "$sourceHash";
 }
"@
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'PackagedInstallerInfo.cs'), $info, [Text.UTF8Encoding]::new($false))
$vcvars = 'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat'
if (!(Test-Path -LiteralPath $vcvars)) { throw 'VS C++ x64 tools unavailable' }
$project = Join-Path $PSScriptRoot 'SpankyNativeBootstrap.csproj'
$publish = Join-Path $root 'artifacts\native-bootstrap-probe'
$command = 'call "' + $vcvars + '" >nul && dotnet publish "' + $project + '" -c Release -r win-x64 --nologo -v:q -p:OS=Windows_NT -p:IlcUseEnvironmentalTools=true -o "' + $publish + '"'
& cmd.exe /d /c $command
if ($LASTEXITCODE -ne 0) { throw 'AOT publish failed' }
$native = Join-Path $publish 'SpankyNativeBootstrap.exe'
$pe = [IO.File]::OpenRead($native)
try {
  $reader = [IO.BinaryReader]::new($pe)
  if ($reader.ReadUInt16() -ne 0x5A4D) { throw 'Native PE DOS header missing' }
  $null = $pe.Seek(0x3c, [IO.SeekOrigin]::Begin)
  $peOffset = $reader.ReadInt32()
  if ($peOffset -lt 64 -or $peOffset -ge $pe.Length-100) { throw 'Invalid native PE offset' }
  $null = $pe.Seek($peOffset+92, [IO.SeekOrigin]::Begin)
  if ($reader.ReadUInt16() -ne 2) { throw 'Native launcher must use Windows GUI subsystem (not a console)' }
} finally { $pe.Dispose() }
Write-Output 'NATIVE_WINDOWS_GUI_SUBSYSTEM_OK'
Copy-Item -LiteralPath $native -Destination $OutputPath -Force
$writer = [IO.File]::Open($OutputPath, [IO.FileMode]::Open, [IO.FileAccess]::Write, [IO.FileShare]::None)
try {
  $null = $writer.Seek(0, [IO.SeekOrigin]::End)
  $reader = [IO.File]::OpenRead($InstallerPath)
  try { $reader.CopyTo($writer, 131072) } finally { $reader.Dispose() }
  $writer.Flush($true)
} finally { $writer.Dispose() }
$nativeUiCases = @('--smoke-native-status','--smoke-native-cancel','--smoke-native-update-stress','--smoke-native-guard-close','--smoke-native-cancel-before-handoff')
foreach ($uiCase in $nativeUiCases) {
  $ui = Start-Process -FilePath $OutputPath -ArgumentList $uiCase -PassThru -Wait
  if ($ui.ExitCode -ne 0) { throw ('Native Win32 UI regression failed '+$uiCase+' exit='+$ui.ExitCode) }
  Write-Output ('NATIVE_GUI_TEST_OK ' + $uiCase)
}
# A real pair of Windows processes must share the same session mutex.
$mutexFolder = Join-Path ([IO.Path]::GetTempPath()) ('spanky-native-mutex-test-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $mutexFolder | Out-Null
$owner = $null
try {
  $owner = Start-Process -FilePath $OutputPath -ArgumentList '--smoke-native-instance-hold' -PassThru
  $marker = Join-Path ([IO.Path]::GetTempPath()) ('spanky-native-hold-' + $owner.Id + '.ready')
  for ($attempt=0; $attempt -lt 80 -and !(Test-Path $marker); $attempt++) {
    if ($owner.HasExited) { throw ('Native mutex owner terminated unexpectedly: ' + $owner.ExitCode) }
    Start-Sleep -Milliseconds 25
  }
  if (!(Test-Path $marker)) { throw 'Native mutex owner did not signal readiness' }
  $contender = Start-Process -FilePath $OutputPath -ArgumentList '--smoke-native-instance-probe' -Wait -PassThru
  if ($contender.ExitCode -ne 60) { throw ('Concurrent native process not blocked; exit=' + $contender.ExitCode) }
  # The explicit installation CLI MUST use this same guard. With the mutex
  # already owned it cannot reach UAC, network, or OS modification.
  $blockedSetup = Start-Process -FilePath $OutputPath -ArgumentList '--launch-packaged-installer' -Wait -PassThru
  if ($blockedSetup.ExitCode -ne 60) { throw ('Explicit installer CLI bypasses mutex; exit=' + $blockedSetup.ExitCode) }
  Write-Output 'NATIVE_INSTALL_CLI_MUTEX_GUARD_OK blocked=60'
  if (!$owner.WaitForExit(6000) -or $owner.ExitCode -ne 0) { throw 'Native mutex owner did not finish normally' }
  $released = Start-Process -FilePath $OutputPath -ArgumentList '--smoke-native-instance-probe' -Wait -PassThru
  if ($released.ExitCode -ne 0) { throw ('Native mutex was not released; exit=' + $released.ExitCode) }
  Write-Output 'NATIVE_SINGLE_INSTANCE_OK contender=60 released=0'
} finally {
  if ($owner -and !$owner.HasExited) { $owner.Kill() }
  if ($owner) { $owner.Dispose() }
  Remove-Item $mutexFolder -Recurse -Force -ErrorAction SilentlyContinue
}
$pinnedLaunch = Start-Process -FilePath $OutputPath -ArgumentList '--smoke-pinned-shell-launch' -PassThru -Wait
if ($pinnedLaunch.ExitCode -ne 0) { throw ('Pinned handle ShellExecute compatibility failed exit='+$pinnedLaunch.ExitCode) }
Write-Output 'NATIVE_PINNED_SHELL_LAUNCH_OK'
$verify = Start-Process -FilePath $OutputPath -ArgumentList '--verify-package' -Wait -PassThru
if ($verify.ExitCode -ne 0) { throw ('Bundled payload verification failed exit='+$verify.ExitCode) }
Write-Output 'NATIVE_OVERLAY_VERIFY_OK waited=true exit=0'
# Full read-only readiness path: same package hash and same runtime check that
# a normal launch uses, without executing the installation.
$runtimeReady = Start-Process -FilePath $OutputPath -ArgumentList '--bootstrap-preflight' -Wait -PassThru
$combined = Start-Process -FilePath $OutputPath -ArgumentList '--preflight-package-ready' -Wait -PassThru
if ($combined.ExitCode -ne $runtimeReady.ExitCode) {
  throw ('Readiness check disagrees with installed runtime state: '+$combined.ExitCode+'/'+$runtimeReady.ExitCode)
}
if ($combined.ExitCode -notin @(0,10)) { throw ('Read-only native readiness check failed: '+$combined.ExitCode) }
Write-Output ('NATIVE_READ_ONLY_FULL_PREFLIGHT_OK status='+$combined.ExitCode)
$testRoot = Join-Path ([IO.Path]::GetTempPath()) ('spanky-native-overlay-test-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $testRoot | Out-Null
try {
  $extracted = Join-Path $testRoot 'extracted.exe'
  $extract = Start-Process -FilePath $OutputPath -ArgumentList @('--extract-package',$extracted) -Wait -PassThru
  if ($extract.ExitCode -ne 0) { throw ('Overlay extraction failed exit='+$extract.ExitCode) }
  if ((Get-FileHash $extracted -Algorithm SHA256).Hash -ne $sourceHash) { throw 'WPF digest mismatch' }
  $smoke = Start-Process -FilePath $extracted -ArgumentList '--release-installer-smoke-bundle' -PassThru -Wait
  if ($smoke.ExitCode -ne 0) { throw ('Bundled WPF smoke failed exit='+$smoke.ExitCode) }
  Write-Output 'NATIVE_TO_WPF_SMOKE_OK waited=true exit=0'
} finally { Remove-Item $testRoot -Recurse -Force -ErrorAction SilentlyContinue }
Write-Output ('NATIVE_OVERLAY_PROTOTYPE_OK nativeBytes='+((Get-Item $native).Length)+' wpfBytes='+$sourceFile.Length+' combinedBytes='+((Get-Item $OutputPath).Length)+' file='+$OutputPath)
